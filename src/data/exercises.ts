import type { TenseId } from './tenses'

export type ExerciseType = 'mcq' | 'fill' | 'transform' | 'match' | 'spot'

export interface Exercise {
  id: string
  tenseId: TenseId
  type: ExerciseType
  prompt: string
  /** Full sentence with ___ for fill, or transform instruction */
  sentence?: string
  options?: string[]
  answer: string
  /** For match: pairs field is source of truth; answer mirrors as left=>right lines */
  pairs?: { left: string; right: string }[]
  tip: string
}

